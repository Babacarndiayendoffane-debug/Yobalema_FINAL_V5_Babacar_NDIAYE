  /// Verifies if a GPS coordinate is strictly inside the administrative boundary of the Kaolack Region.
  /// Uses bounding box pre-filter followed by ray-casting point-in-polygon algorithm.
  static bool isInside(LatLng point) {
    final lat = point.latitude;
    final lng = point.longitude;

    if (lat < minLat || lat > maxLat || lng < minLng || lng > maxLng) {
      return false;
    }

    bool inside = false;
    for (int i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
      final xi = polygon[i].longitude;
      final yi = polygon[i].latitude;
      final xj = polygon[j].longitude;
      final yj = polygon[j].latitude;

      final intersect = ((yi > lat) != (yj > lat)) &&
          (lng < (xj - xi) * (lat - yi) / (yj - yi) + xi);
      if (intersect) inside = !inside;
    }
    return inside;
  }
